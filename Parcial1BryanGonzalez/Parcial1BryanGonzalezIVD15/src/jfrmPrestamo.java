    private void jbtCalculoPagosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtCalculoPagosActionPerformed
        // TODO add your handling code here:
        try {
    if (jtfCredito.getText().trim().isEmpty() ||
        jtfPeriodoMin.getText().trim().isEmpty() ||
        jtfPeriodoMax.getText().trim().isEmpty() ||
        jtfInteresMax.getText().trim().isEmpty() ||
        jtfInteresMin.getText().trim().isEmpty()) {
        
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor llena todos los campos de texto.");
        return;
    }

    credito = Double.parseDouble(jtfCredito.getText());
    periodoMin = Integer.parseInt(jtfPeriodoMin.getText());
    periodoMax = Integer.parseInt(jtfPeriodoMax.getText());
    interesMax = Double.parseDouble(jtfInteresMax.getText());
    interesMin = Double.parseDouble(jtfInteresMin.getText());
    incremento = Double.parseDouble(jcbIncremento.getSelectedItem().toString());

    añosMeses = periodoMax - periodoMin + 1;
    tiposIntrs = (int) Math.round((interesMax - interesMin) / incremento) + 1;

    initTable(tiposIntrs, añosMeses + 1);

    double intrs = interesMin;
    for (int i = 0; i < tiposIntrs; i++) {
        jtablaCabsFilas.setValueAt(String.format("%.2f%%", intrs), i, 0);
        int j = 1;
        for (int p = periodoMin; p <= periodoMax; p++) {
            double r = (intrs / 100) / 12;
            int n = p * 12;
            double cuota = (r == 0) ? (credito / n) : (credito * r) / (1 - Math.pow(1 + r, -n));
            jtablaPrestamo.setValueAt(String.format("%.2f", cuota), i, j - 1);
            j++;
        }
        intrs += incremento;
    }
} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Revisa que los campos tengan datos válidos.");
}
    }//GEN-LAST:event_jbtCalculoPagosActionPerformed


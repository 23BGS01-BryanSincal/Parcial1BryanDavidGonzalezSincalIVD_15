    private void jbtCalculoAmortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtCalculoAmortActionPerformed
        // TODO add your handling code here:
        int filaSel = jtablaPrestamo.getSelectedRow();
int colSel = jtablaPrestamo.getSelectedColumn();

if (filaSel == -1 || colSel == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Por favor selecciona primero una celda de la tabla.");
    return;
}

try {
    double interes = interesMin + (filaSel * incremento);
    int plazo = periodoMin + colSel;
    double cuota = Double.parseDouble(jtablaPrestamo.getValueAt(filaSel, colSel).toString());
    
    boolean esModoMeses = !JmItemMeses.isEnabled();
    int totalMeses = esModoMeses ? plazo : plazo * 12;

    StringBuilder sb = new StringBuilder();
    sb.append(String.format("Tabla de Amortización para un préstamo de $%.2f\n", credito));
    sb.append(String.format("Tasa: %.2f%% | Plazo: %d %s | Cuota Mensual: $%.2f\n\n", 
            interes, plazo, (esModoMeses ? "meses" : "años"), cuota));
    sb.append(String.format("%-6s | %-12s | %-12s | %-12s\n", "Mes", "Interés", "Capital", "Saldo Pend."));
    sb.append("-----------------------------------------------------------\n");

    double saldo = credito;
    double r = (interes / 100) / 12;

    for (int m = 1; m <= totalMeses; m++) {
        double intMes = saldo * r;
        double capMes = cuota - intMes;
        saldo -= capMes;
        if (saldo < 0) saldo = 0;

        sb.append(String.format("%-6d | $%-11.2f | $%-11.2f | $%-11.2f\n", m, intMes, capMes, saldo));
    }

    javax.swing.JTextArea textArea = new javax.swing.JTextArea(sb.toString());
    textArea.setRows(15);
    textArea.setColumns(45);
    textArea.setEditable(false);
    
    javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(textArea);
    javax.swing.JOptionPane.showMessageDialog(this, scroll, "Tabla de Amortización", javax.swing.JOptionPane.INFORMATION_MESSAGE);

} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Asegúrate de haber generado primero la tabla con el botón Pagos.");
}
    }//GEN-LAST:event_jbtCalculoAmortActionPerformed

